import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {index,validate} from '../dist/engine.mjs';
import {CLADE_GROUPS,remapCladeView} from '../dist/clades.mjs';
const b=JSON.parse(readFileSync(new URL('../dist/data.json',import.meta.url)));
const plain=index(b),tree=index(b,'global','all','',null,true);
assert.equal(tree.overlay.active,true);assert.equal(tree.root.count,plain.root.count);assert.deepEqual(tree.root.children.map(id=>tree.byid.get(id).name),['Palaeognathae','Neognathae']);
assert.equal(tree.byid.get('phylo:palaeognathae').count,60);
assert.equal(tree.byid.get('phylo:galloanserae').count,483);
assert.equal(tree.byid.get('phylo:neoaves').count,tree.root.count-543);
assert.equal(tree.byid.get('phylo:neognathae').count,tree.root.count-60);
assert.equal(new Set(CLADE_GROUPS.flatMap(g=>g.orders||[])).size,45);
for(const n of b.nodes.filter(n=>n.rank==='order'))assert.equal(tree.byid.get(n.id).count,plain.byid.get(n.id).count);
for(const scope of ['global','germany'])for(const query of ['','Kohlmeise','Neoaves']){const v=index(b,scope,'all',query,null,true);assert.equal(v.root.count,v.byid.get('phylo:palaeognathae').count+v.byid.get('phylo:neognathae').count);assert.equal(v.byid.get('phylo:neognathae').count,v.byid.get('phylo:galloanserae').count+v.byid.get('phylo:neoaves').count);}
const one=b.nodes.find(n=>n.rank==='order'&&n.name==='Passeriformes');assert.equal(index(b,'germany','all','',new Set([one.id]),true).root.count,index(b,'germany','all','',new Set([one.id])).root.count);
const next=structuredClone(b);next.nodes.find(n=>n.rank==='order').name='ChangedOrder';const fallback=index(next,'global','all','',null,true);assert.equal(fallback.overlay.active,false);assert.equal(fallback.root.children.length,45);assert.deepEqual(fallback.overlay.unknown,['ChangedOrder']);
const injected=structuredClone(b);injected.nodes.push({id:'phylo:bad',rank:'clade',name:'Fake',parent:b.nodes[0].id});assert(validate(injected).some(e=>e.includes('Kladen gehören nicht')));
const passerine=b.nodes.find(n=>n.rank==='order'&&n.name==='Passeriformes');
const species=b.nodes.find(n=>n.rank==='species'&&n.name==='Parus major');
const genus=b.nodes.find(n=>n.rank==='genus'&&n.name==='Parus');
const family=b.nodes.find(n=>n.rank==='family'&&n.name==='Paridae');
const expanded=new Set([plain.root.id,passerine.id,family.id,genus.id]);
const on=remapCladeView(plain,tree,plain.root.id,species.id,expanded);
assert.equal(on.focusId,tree.root.id);assert.equal(on.selectedId,species.id);
assert.deepEqual([...on.open].filter(id=>id.startsWith('phylo:')).sort(),['phylo:neoaves','phylo:neognathae']);
for(const id of expanded)assert(on.open.has(id));
const off=remapCladeView(tree,plain,on.focusId,on.selectedId,on.open);
assert.equal(off.selectedId,species.id);assert.deepEqual(off.open,expanded);
const focused=remapCladeView(plain,tree,passerine.id,species.id,new Set([passerine.id,family.id,genus.id]));
assert.equal(focused.focusId,passerine.id);assert.equal(focused.open.size,3);
const synthetic=remapCladeView(tree,plain,'phylo:neoaves','phylo:neoaves',new Set(['phylo:neoaves',passerine.id]));
assert.equal(synthetic.focusId,plain.root.id);assert.equal(synthetic.selectedId,null);
assert.deepEqual(synthetic.open,new Set([passerine.id,plain.root.id]));
console.log('PASS: optionale Kladen, Summen, Filter, Suche, unveränderte Ordnungsknoten und sichere Deaktivierung bei unbekannten Ordnungen.');
